"""
The checkerboard of the challenge, as an SDF model.

    8 x 8 squares of 30 mm  ->  a 240 mm x 240 mm playing area  (Challenge, Sec. 2)

This file is the single source of the model: models/checkerboard/model.sdf is its
output. To change a dimension, change it here and regenerate:

    python3 -m lite6_checkers.make_board_sdf > models/checkerboard/model.sdf

Board frame (the model origin)
------------------------------
    origin   centre of the playing area, ON the playing surface (z = 0); the slab
             of the board is below it, z in [-thickness, 0].
    x        from White's side to Black's side (the direction in which the men
             advance), so that the board frame can be laid with the same yaw as a
             robot facing the board.
    y        to White's left, i.e. towards the a-file; z up (right-handed).

Squares are named as in the rules: file a..h (y decreasing), rank 1..8 (x increasing).
a1 is a dark square at White's left-hand corner, so the long dark diagonal a1-h8
runs to each player's left, as the Reference rules require (Sec. 1.1). A square is
dark when (file + rank) is even, counting from 0.
"""
import sys

SQUARES = 8
SQUARE = 0.030          # m, square side: the challenge's 30 mm
BORDER = 0.012          # m, frame around the playing area (cosmetic, not in the challenge)
THICKNESS = 0.010       # m, thickness of the board slab

# Lightness is what matters for the camera extension; hue is only cosmetic.
LIGHT = (0.93, 0.86, 0.70)
DARK = (0.32, 0.19, 0.10)
FRAME = (0.20, 0.12, 0.07)

# The dark squares stand 0.5 mm proud of the light plate, so their top faces and the
# plate's do not fight in the renderer. The collision surface is one flat box whose top
# is at z = 0: a piece pushed across the board never meets a step.
PROUD = 0.0005


def _material(rgb):
    r, g, b = rgb
    return (f'<material><ambient>{r} {g} {b} 1</ambient><diffuse>{r} {g} {b} 1</diffuse>'
            f'<specular>0.05 0.05 0.05 1</specular></material>')


def _box_visual(name, size, pose, rgb):
    sx, sy, sz = size
    x, y, z = pose
    return (f'      <visual name="{name}">\n'
            f'        <pose>{x:.6f} {y:.6f} {z:.6f} 0 0 0</pose>\n'
            f'        <geometry><box><size>{sx:.6f} {sy:.6f} {sz:.6f}</size></box></geometry>\n'
            f'        {_material(rgb)}\n'
            f'      </visual>\n')


def square_centre(file_index, rank_index, square=SQUARE, squares=SQUARES):
    """(x, y) of the centre of square (file_index, rank_index), both counted from 0, in the board frame."""
    half = (squares - 1) / 2.0
    return (rank_index - half) * square, (half - file_index) * square


def is_dark(file_index, rank_index):
    return (file_index + rank_index) % 2 == 0


def board_sdf(square=SQUARE, border=BORDER, thickness=THICKNESS, squares=SQUARES):
    play = squares * square
    outer = play + 2 * border
    plate = 0.001   # thickness of the light plate and of the dark squares

    v = []
    # The slab: frame colour, its top 1 mm below the playing surface.
    v.append(_box_visual('frame', (outer, outer, thickness - plate),
                         (0, 0, -plate - (thickness - plate) / 2), FRAME))
    # The light plate under the whole playing area.
    v.append(_box_visual('light_plate', (play, play, plate),
                         (0, 0, -PROUD - plate / 2), LIGHT))
    # The 32 dark squares, named by their square.
    for f in range(squares):
        for r in range(squares):
            if is_dark(f, r):
                x, y = square_centre(f, r, square, squares)
                v.append(_box_visual(f'dark_{"abcdefgh"[f]}{r + 1}', (square, square, plate),
                                     (x, y, -plate / 2), DARK))

    return (
        '<?xml version="1.0"?>\n'
        '<!-- GENERATED by lite6_checkers.make_board_sdf: edit that file, not this one. -->\n'
        '<sdf version="1.9">\n'
        '  <model name="checkerboard">\n'
        '    <static>true</static>\n'
        '    <link name="board">\n'
        '      <collision name="surface">\n'
        f'        <pose>0 0 {-thickness / 2:.6f} 0 0 0</pose>\n'
        f'        <geometry><box><size>{outer:.6f} {outer:.6f} {thickness:.6f}</size></box></geometry>\n'
        '        <surface><friction><ode><mu>0.6</mu><mu2>0.6</mu2></ode></friction></surface>\n'
        '      </collision>\n'
        + ''.join(v) +
        '    </link>\n'
        '  </model>\n'
        '</sdf>\n')


def main():
    sys.stdout.write(board_sdf())


if __name__ == '__main__':
    main()
