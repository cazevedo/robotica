"""
The pieces of the challenge, as SDF models.

    Laboratory-supplied: disc base D 24 mm x 10 mm, with a central peg D 11 mm x 15 mm.
    Two colours, plus marked dama pieces.                                (Challenge, Sec. 2)

The peg is the handle: the gripper opens to 16 mm, a flat disc cannot be grasped from the side, so
the gripper closes on the peg (Challenge, Sec. 2.1). The base is what a pushed piece is pushed on:
its top is 10 mm above the board, and the centre of mass of the piece, which the push must stay
below, is at about 8 mm.

This file is the single source of the models: models/<name>/model.sdf are its output.

    python3 -m lite6_checkers.make_piece_sdf models/

Four models are written: checker_white, checker_black (men), dama_white, dama_black (the same piece
with a gold cap on the peg, which is only a mark: the shape, mass and grasp are those of a man).

Piece frame (the model origin)
------------------------------
    origin   centre of the underside of the base: the model rests on the board plane at z = 0.
    z        up, along the peg.
"""
import math
import pathlib
import sys

BASE_D = 0.024          # m
BASE_H = 0.010
PEG_D = 0.011
PEG_H = 0.015
CAP_H = 0.004           # m, the gold cap of a dama, the top of the peg
DENSITY = 1200.0        # kg/m^3, solid plastic
MU = 0.5                # friction coefficient piece/board (the board's is 0.6)

COLOURS = {
    'white': (0.95, 0.94, 0.88),
    'black': (0.07, 0.07, 0.08),
}
GOLD = (0.83, 0.65, 0.13)


def mass_properties():
    """(mass, z of the centre of mass, Ixx = Iyy, Izz about the centre of mass) of the piece."""
    m1 = DENSITY * math.pi * (BASE_D / 2) ** 2 * BASE_H
    m2 = DENSITY * math.pi * (PEG_D / 2) ** 2 * PEG_H
    z1, z2 = BASE_H / 2, BASE_H + PEG_H / 2
    m = m1 + m2
    zc = (m1 * z1 + m2 * z2) / m

    def ixx(mi, r, h):
        return mi * (3 * r * r + h * h) / 12

    def izz(mi, r):
        return mi * r * r / 2

    Ixx = (ixx(m1, BASE_D / 2, BASE_H) + m1 * (zc - z1) ** 2
           + ixx(m2, PEG_D / 2, PEG_H) + m2 * (zc - z2) ** 2)
    Izz = izz(m1, BASE_D / 2) + izz(m2, PEG_D / 2)
    return m, zc, Ixx, Izz


def _material(rgb):
    r, g, b = rgb
    return (f'<material><ambient>{r} {g} {b} 1</ambient><diffuse>{r} {g} {b} 1</diffuse>'
            f'<specular>0.2 0.2 0.2 1</specular></material>')


def _cylinder(kind, name, d, h, z, rgb=None):
    mat = f'\n        {_material(rgb)}' if rgb else ''
    return (f'      <{kind} name="{name}">\n'
            f'        <pose>0 0 {z:.6f} 0 0 0</pose>\n'
            f'        <geometry><cylinder><radius>{d / 2:.6f}</radius><length>{h:.6f}</length></cylinder></geometry>'
            f'{mat}\n'
            f'      </{kind}>\n')


def piece_sdf(colour, dama=False):
    rgb = COLOURS[colour]
    m, zc, Ixx, Izz = mass_properties()
    name = f'{"dama" if dama else "checker"}_{colour}'

    visuals = _cylinder('visual', 'base', BASE_D, BASE_H, BASE_H / 2, rgb)
    if dama:
        low = PEG_H - CAP_H
        visuals += _cylinder('visual', 'peg', PEG_D, low, BASE_H + low / 2, rgb)
        visuals += _cylinder('visual', 'cap', PEG_D, CAP_H, BASE_H + low + CAP_H / 2, GOLD)
    else:
        visuals += _cylinder('visual', 'peg', PEG_D, PEG_H, BASE_H + PEG_H / 2, rgb)

    surface = (f'        <surface><friction><ode><mu>{MU}</mu><mu2>{MU}</mu2></ode></friction></surface>\n')
    collisions = (_cylinder('collision', 'base', BASE_D, BASE_H, BASE_H / 2).replace(
                      '      </collision>', surface + '      </collision>')
                  + _cylinder('collision', 'peg', PEG_D, PEG_H, BASE_H + PEG_H / 2).replace(
                      '      </collision>', surface + '      </collision>'))

    return (
        '<?xml version="1.0"?>\n'
        '<!-- GENERATED by lite6_checkers.make_piece_sdf: edit that file, not this one. -->\n'
        '<sdf version="1.9">\n'
        f'  <model name="{name}">\n'
        '    <link name="piece">\n'
        '      <inertial>\n'
        f'        <pose>0 0 {zc:.6f} 0 0 0</pose>\n'
        f'        <mass>{m:.6f}</mass>\n'
        f'        <inertia><ixx>{Ixx:.4e}</ixx><iyy>{Ixx:.4e}</iyy><izz>{Izz:.4e}</izz>'
        '<ixy>0</ixy><ixz>0</ixz><iyz>0</iyz></inertia>\n'
        '      </inertial>\n'
        + collisions + visuals +
        '    </link>\n'
        '  </model>\n'
        '</sdf>\n')


def model_config(name, colour, dama):
    what = 'dama (crowned man, gold-capped peg)' if dama else 'man'
    return ('<?xml version="1.0"?>\n'
            '<model>\n'
            f'  <name>{name}</name>\n'
            '  <version>1.0</version>\n'
            '  <sdf version="1.9">model.sdf</sdf>\n'
            '  <author>\n    <name>cazevedo</name>\n    <email>cazevedo@ipn.pt</email>\n  </author>\n'
            f'  <description>Draughts {what}, {colour}: base D 24 x 10 mm, peg D 11 x 15 mm.</description>\n'
            '</model>\n')


def models():
    """{model name: (model.sdf text, model.config text)} for the four pieces."""
    out = {}
    for colour in COLOURS:
        for dama in (False, True):
            name = f'{"dama" if dama else "checker"}_{colour}'
            out[name] = (piece_sdf(colour, dama), model_config(name, colour, dama))
    return out


def main():
    if len(sys.argv) != 2:
        sys.exit('usage: python3 -m lite6_checkers.make_piece_sdf MODELS_DIR')
    root = pathlib.Path(sys.argv[1])
    for name, (sdf, config) in models().items():
        d = root / name
        d.mkdir(parents=True, exist_ok=True)
        (d / 'model.sdf').write_text(sdf, newline='\n')
        (d / 'model.config').write_text(config, newline='\n')
        print(f'wrote {d}')


if __name__ == '__main__':
    main()
